def get_stats():
    conn = get_db_connection()
    cursor = conn.cursor()

    cursor.execute("SELECT COUNT(*) AS count FROM trips")
    total_trips = cursor.fetchone()["count"]

    cursor.execute("SELECT SUM(distance_km) AS total FROM trips")
    total_dist = cursor.fetchone()["total"] or 0.0

    cursor.execute("SELECT COUNT(*) AS count FROM refuel_logs")
    total_refuels = cursor.fetchone()["count"]

    cursor.execute("SELECT SUM(cost) AS total FROM refuel_logs")
    total_spend = cursor.fetchone()["total"] or 0.0

    cursor.execute("SELECT SUM(liters) AS total FROM refuel_logs")
    total_liters = cursor.fetchone()["total"] or 0.0

    cursor.execute("SELECT COUNT(*) AS count FROM bikes")
    total_bikes = cursor.fetchone()["count"]

    cursor.close()
    conn.close()

    return {
        "total_trips": total_trips,
        "total_distance_km": round(float(total_dist), 2),
        "total_refuels": total_refuels,
        "total_spend": round(float(total_spend), 2),
        "total_liters": round(float(total_liters), 2),
        "total_bikes": total_bikes
    }


