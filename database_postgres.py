import os
import psycopg2
from psycopg2.extras import RealDictCursor
from psycopg2 import IntegrityError
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is not set in .env")


def get_db_connection():
    return psycopg2.connect(
        DATABASE_URL,
        cursor_factory=RealDictCursor
    )


def init_db():
    conn = get_db_connection()
    cursor = conn.cursor()

    # 1. Create Bikes Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS bikes (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT UNIQUE NOT NULL,
            base_mileage REAL NOT NULL,
            tank_capacity REAL NOT NULL DEFAULT 10.0
        )
    """)

    # 2. Create Trips Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS trips (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            start_location TEXT,
            end_location TEXT,
            bike_name TEXT,
            speed REAL,
            fuel_input REAL,
            road_type TEXT,
            load_type TEXT,
            predicted_mileage REAL,
            predicted_range REAL,
            distance_km REAL,
            duration_hours REAL,
            status TEXT,
            fuel_needed REAL
        )
    """)

    # 3. Create Refueling Logs Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS refuel_logs (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            date TEXT NOT NULL,
            liters REAL NOT NULL,
            price_per_liter REAL NOT NULL,
            cost REAL NOT NULL,
            odometer REAL NOT NULL,
            notes TEXT
        )
    """)

    # 4. Create Users Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            phone TEXT UNIQUE NOT NULL,
            name TEXT NOT NULL,
            bike_name TEXT DEFAULT 'Hero Splendor',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # 5. Create Group Rides Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS group_rides (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code TEXT UNIQUE NOT NULL,
            name TEXT NOT NULL,
            created_by TEXT NOT NULL,
            status TEXT DEFAULT 'ACTIVE',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # 6. Create Group Riders Table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS group_riders (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_id INTEGER NOT NULL,
            rider_id TEXT NOT NULL,
            rider_label TEXT NOT NULL,
            rider_name TEXT NOT NULL,
            bike_name TEXT NOT NULL,
            lat REAL NOT NULL,
            lon REAL NOT NULL,
            fuel REAL NOT NULL,
            fuel_range REAL NOT NULL,
            mileage REAL NOT NULL,
            speed REAL NOT NULL,
            status TEXT NOT NULL DEFAULT 'Cruising',
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(group_id, rider_id),
            FOREIGN KEY (group_id)
                REFERENCES group_rides(id)
                ON DELETE CASCADE
        )
    """)

    # Prepopulate default bikes if table is empty
    cursor.execute("SELECT COUNT(*) FROM bikes")
    if cursor.fetchone()["count"] == 0:
        default_bikes = [
            ("Hero Splendor", 60.0, 9.8),
            ("Honda Shine", 55.0, 10.5),
            ("Bajaj Pulsar 150", 45.0, 15.0),
            ("TVS Apache", 40.0, 12.0)
        ]

        cursor.executemany(
            """
            INSERT INTO bikes (name, base_mileage, tank_capacity)
            VALUES (%s, %s, %s)
            ON CONFLICT (name) DO NOTHING
            """,
            default_bikes
        )

    conn.commit()
    cursor.close()
    conn.close()


