def join_group_ride(
    code,
    rider_id,
    rider_name,
    bike_name,
    lat,
    lon,
    fuel=2.5,
    speed=50.0,
    fuel_range=120.0,
    mileage=50.0,
    status="Cruising"
):
    code = code.strip().upper()

    conn = get_db_connection()
    cursor = conn.cursor()

    cursor.execute(
        "SELECT * FROM group_rides WHERE code = %s",
        (code,)
    )

    ride = cursor.fetchone()

    if not ride:
        cursor.close()
        conn.close()

        return None, "Group ride not found"

    group_id = ride["id"]

    cursor.execute(
        """
        SELECT *
        FROM group_riders
        WHERE group_id = %s AND rider_id = %s
        """,
        (
            group_id,
            str(rider_id)
        )
    )

    existing = cursor.fetchone()

    if existing:
        label = existing["rider_label"]

        cursor.execute(
            """
            UPDATE group_riders
            SET rider_name = %s,
                bike_name = %s,
                lat = %s,
                lon = %s,
                fuel = %s,
                speed = %s,
                fuel_range = %s,
                mileage = %s,
                status = %s,
                updated_at = CURRENT_TIMESTAMP
            WHERE id = %s
            """,
            (
                rider_name,
                bike_name,
                lat,
                lon,
                fuel,
                speed,
                fuel_range,
                mileage,
                status,
                existing["id"]
            )
        )

        conn.commit()

        cursor.execute(
            "SELECT * FROM group_riders WHERE id = %s",
            (existing["id"],)
        )

        updated = cursor.fetchone()

        cursor.close()
        conn.close()

        return dict(updated), None

    cursor.execute(
        """
        SELECT rider_label
        FROM group_riders
        WHERE group_id = %s
        ORDER BY id ASC
        """,
        (group_id,)
    )

    current_riders = cursor.fetchall()

    used_labels = {
        r["rider_label"]
        for r in current_riders
    }

    assigned_label = None

    for lbl in RIDER_LABELS:
        if lbl not in used_labels:
            assigned_label = lbl
            break

    if not assigned_label:
        assigned_label = f"Rider {chr(65 + len(used_labels))}"

    cursor.execute(
        """
        INSERT INTO group_riders (
            group_id,
            rider_id,
            rider_label,
            rider_name,
            bike_name,
            lat,
            lon,
            fuel,
            fuel_range,
            mileage,
            speed,
            status
        )
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        """,
        (
            group_id,
            str(rider_id),
            assigned_label,
            rider_name,
            bike_name,
            lat,
            lon,
            fuel,
            fuel_range,
            mileage,
            speed,
            status
        )
    )

    conn.commit()

    cursor.execute(
        """
        SELECT *
        FROM group_riders
        WHERE group_id = %s AND rider_id = %s
        """,
        (
            group_id,
            str(rider_id)
        )
    )

    new_rider = cursor.fetchone()

    cursor.close()
    conn.close()

    return dict(new_rider), None


