def get_or_create_user(phone, name=None, bike_name="Hero Splendor"):
    phone = str(phone).strip()

    conn = get_db_connection()
    cursor = conn.cursor()

    cursor.execute(
        "SELECT * FROM users WHERE phone = %s",
        (phone,)
    )

    user = cursor.fetchone()

    if user:
        if name and name.strip() and user["name"] != name.strip():

            cursor.execute(
                """
                UPDATE users
                SET name = %s, bike_name = %s
                WHERE phone = %s
                """,
                (
                    name.strip(),
                    bike_name or user["bike_name"],
                    phone
                )
            )

            conn.commit()

            cursor.execute(
                "SELECT * FROM users WHERE phone = %s",
                (phone,)
            )

            user = cursor.fetchone()

        cursor.close()
        conn.close()

        return dict(user)

    user_name = (
        name.strip()
        if name and name.strip()
        else f"Rider {phone[-4:]}"
    )

    cursor.execute(
        """
        INSERT INTO users (phone, name, bike_name)
        VALUES (%s, %s, %s)
        """,
        (
            phone,
            user_name,
            bike_name or "Hero Splendor"
        )
    )

    conn.commit()

    cursor.execute(
        "SELECT * FROM users WHERE phone = %s",
        (phone,)
    )

    user = cursor.fetchone()

    cursor.close()
    conn.close()

    return dict(user)


