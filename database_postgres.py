def update_rider_telemetry(
    code,
    rider_id,
    lat,
    lon,
    fuel=None,
    speed=None,
    status=None,
    fuel_range=None,
    mileage=None
):
    code = code.strip().upper()

    conn = get_db_connection()
    cursor = conn.cursor()

    cursor.execute(
        "SELECT id FROM group_rides WHERE code = %s",
        (code,)
    )

    ride = cursor.fetchone()

    if not ride:
        cursor.close()
        conn.close()

        return None

    group_id = ride["id"]

    cursor.execute(
        """
        SELECT *
        FROM group_riders
        WHERE group_id = %s AND rider_id = %s
        """,
        (
            group_id,
            str(rider_id)
        )
    )

    rider = cursor.fetchone()

    if not rider:
        cursor.close()
        conn.close()

        return None

    new_lat = float(lat) if lat is not None else rider["lat"]
    new_lon = float(lon) if lon is not None else rider["lon"]
    new_fuel = float(fuel) if fuel is not None else rider["fuel"]
    new_speed = float(speed) if speed is not None else rider["speed"]
    new_status = str(status) if status is not None else rider["status"]
    new_fuel_range = (
        float(fuel_range)
        if fuel_range is not None
        else rider["fuel_range"]
    )
    new_mileage = (
        float(mileage)
        if mileage is not None
        else rider["mileage"]
    )

    # Auto status update if fuel is critically low
    if new_fuel <= 1.0 and new_status not in ["Refueling", "Stopped"]:
        new_status = "Low Fuel Warning"

    cursor.execute(
        """
        UPDATE group_riders
        SET lat = %s,
            lon = %s,
            fuel = %s,
            speed = %s,
            status = %s,
            fuel_range = %s,
            mileage = %s,
            updated_at = CURRENT_TIMESTAMP
        WHERE id = %s
        """,
        (
            new_lat,
            new_lon,
            new_fuel,
            new_speed,
            new_status,
            new_fuel_range,
            new_mileage,
            rider["id"]
        )
    )

    conn.commit()

    cursor.execute(
        "SELECT * FROM group_riders WHERE id = %s",
        (rider["id"],)
    )

    updated = cursor.fetchone()

    cursor.close()
    conn.close()

    return dict(updated)


